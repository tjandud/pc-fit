-- 1. users table
CREATE TABLE IF NOT EXISTS public.users (
  id UUID PRIMARY KEY DEFAULT auth.uid(),
  username TEXT UNIQUE NOT NULL,
  nickname TEXT UNIQUE NOT NULL,
  profile_image TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. builds table
CREATE TABLE IF NOT EXISTS public.builds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  prompt TEXT NOT NULL,
  parts JSONB NOT NULL,
  total_price INTEGER NOT NULL,
  total_wattage INTEGER NOT NULL,
  psu_wattage INTEGER NOT NULL,
  status TEXT DEFAULT 'private' CHECK (status IN ('private', 'takeoff_pending', 'approved', 'rejected')),
  views INTEGER DEFAULT 0,
  vote_approve INTEGER DEFAULT 0,
  vote_reject INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. takeoff_votes table
CREATE TABLE IF NOT EXISTS public.takeoff_votes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  build_id BIGINT REFERENCES public.builds(id) ON DELETE CASCADE,
  user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  vote_type TEXT NOT NULL CHECK (vote_type IN ('approve', 'reject')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE(build_id, user_id)
);

-- Enable RLS (Row Level Security)
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.builds ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.takeoff_votes ENABLE ROW LEVEL SECURITY;

-- Simple Policies (Everyone can read public data, users can only modify their own)
CREATE POLICY "Users can read all user profiles" ON public.users FOR SELECT USING (true);
CREATE POLICY "Users can update own profile" ON public.users FOR UPDATE USING (auth.uid() = id);

CREATE POLICY "Public builds are viewable by everyone" ON public.builds FOR SELECT USING (status != 'private' OR auth.uid() = user_id);
CREATE POLICY "Users can insert their own builds" ON public.builds FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users can update their own builds" ON public.builds FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "Votes are viewable by everyone" ON public.takeoff_votes FOR SELECT USING (true);
CREATE POLICY "Authenticated users can vote" ON public.takeoff_votes FOR INSERT WITH CHECK (auth.role() = 'authenticated');

-- 4. RPC Functions for Atomic Increments
CREATE OR REPLACE FUNCTION increment_views(build_id_param BIGINT)
RETURNS void AS $$
BEGIN
  UPDATE public.builds
  SET views = views + 1
  WHERE id = build_id_param;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION increment_vote_approve(build_id_param BIGINT)
RETURNS void AS $$
BEGIN
  UPDATE public.builds
  SET vote_approve = vote_approve + 1
  WHERE id = build_id_param;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION increment_vote_reject(build_id_param BIGINT)
RETURNS void AS $$
BEGIN
  UPDATE public.builds
  SET vote_reject = vote_reject + 1
  WHERE id = build_id_param;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
