-- 1. 기존 users 테이블 확장 (비밀번호, 현재PC, 레벨 컬럼 추가)
ALTER TABLE public.users 
ADD COLUMN IF NOT EXISTS password TEXT,
ADD COLUMN IF NOT EXISTS my_pc JSONB,
ADD COLUMN IF NOT EXISTS user_level TEXT DEFAULT 'newbie';

-- 2. 부품 마스터 테이블 (검색용)
CREATE TABLE IF NOT EXISTS public.parts (
  id TEXT PRIMARY KEY, -- opendb_id
  category TEXT NOT NULL,
  name TEXT NOT NULL,
  manufacturer TEXT,
  specs JSONB,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 3. 내 PC 정보 테이블 (상세 저장용)
CREATE TABLE IF NOT EXISTS public.user_pcs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  cpu JSONB,
  gpu JSONB,
  ram JSONB,
  motherboard JSONB,
  storage JSONB,
  psu JSONB,
  pccase JSONB,
  cooler JSONB,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 4. 저장된 견적 테이블 (1, 2, 3지망 데이터 포함)
CREATE TABLE IF NOT EXISTS public.saved_builds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  build_data JSONB NOT NULL, -- 1~3지망 옵션 전체 저장
  total_price INTEGER NOT NULL,
  purpose TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 5. 이륙심사소 게시글 테이블
CREATE TABLE IF NOT EXISTS public.takeoff_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  build_id BIGINT REFERENCES public.saved_builds(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  content TEXT,
  build_snapshot JSONB, -- 게시 시점의 견적 정보
  votes_good INTEGER DEFAULT 0,
  votes_bad INTEGER DEFAULT 0,
  hits INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- RLS 정책 설정 (간단하게 모든 로그인 유저 허용)
ALTER TABLE public.parts ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Everyone can read parts" ON public.parts FOR SELECT USING (true);

ALTER TABLE public.user_pcs ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can manage own pc info" ON public.user_pcs FOR ALL USING (auth.uid() = user_id);

ALTER TABLE public.saved_builds ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can manage own builds" ON public.saved_builds FOR ALL USING (auth.uid() = user_id);

ALTER TABLE public.takeoff_posts ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Everyone can read posts" ON public.takeoff_posts FOR SELECT USING (true);
CREATE POLICY "Users can manage own posts" ON public.takeoff_posts FOR ALL USING (auth.uid() = user_id);

-- 6. 이륙심사소 댓글 테이블
CREATE TABLE IF NOT EXISTS public.comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  build_id BIGINT REFERENCES public.takeoff_posts(id) ON DELETE CASCADE,
  user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  type TEXT DEFAULT 'comment',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

ALTER TABLE public.comments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Everyone can read comments" ON public.comments FOR SELECT USING (true);
CREATE POLICY "Users can manage own comments" ON public.comments FOR ALL USING (auth.uid() = user_id);